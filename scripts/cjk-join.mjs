/**
 * 找**跨行折出来的中文句子中间那个半角空格**。
 *
 * 起因：JSX 把同一个元素里两行文本用**一个空格**连起来——源码里的换行不是免费的。
 * 英文里这叫正常（"Hello" + "World" 本来就该有一个空格），中文里凭空多一道缝：
 * 「…只管书架外观，␣以及字体和引擎装了哪些」「…还扫不扫这个文件夹」。␣」。
 * 2026-10-02 一轮 Design QA 在**跑着的实例**里读 `innerText` 当场量到，
 * 同源脚本扫出 55 处。
 *
 * **为什么现有的闸门一条都不报**：`audit.mjs` 量的是版面（溢出 / 截断 / 对比度 /
 * 点击目标 / 最后一行只剩一个字），`keyboard.mjs` 量的是焦点和名字——
 * 中间多一个空格既不撑破版面也不影响 Tab，八条判据全都安静。
 * 所以这条判据只能做成静态的：判据硬、结果二值，和「写死的按键名」同一路数。
 *
 * 改法只有一个字都不动的那种：**两行并一行**。
 *
 * 跑法：`node scripts/cjk-join.mjs`（在 `lint:ui` 里）
 */
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const 目录 = 'src/renderer';

/** 汉字 + 中文标点。「＋ 新建」那种半角加号后面的空格不算，所以不含 ASCII */
const 中 = '[\\u3400-\\u4dbf\\u4e00-\\u9fff\\u3001-\\u300f\\uff01-\\uff5e\\u300c-\\u300f]';
const 行尾是中文 = new RegExp(`${中}$`);
const 行首是中文 = new RegExp(`^${中}`);
/**
 * **全角标点单独算一类**：逗号句号后面本来就有间距，再折进一个半角空格就是两道缝。
 * 这一类连「下一行是英文」也要报——「…完整阅读，␣pdf / epub 有内置查看器」
 * 就是这么从「两边都是中文」那条规则底下漏掉的（首屏实拍量到）。
 */
const 行尾是全角标点 = /[，。、；：！？）］」』]$/;

const 找文件 = (d, out = []) => {
  for (const e of readdirSync(d, { withFileTypes: true })) {
    const p = join(d, e.name);
    if (e.isDirectory()) 找文件(p, out);
    else if (e.name.endsWith('.tsx') && !/\.test\.tsx$/.test(e.name)) out.push(p);
  }
  return out;
};

/** 注释行、以及 JSX 注释 `{/* … *\/}` 那两头的行都不算上屏文案 */
const 是注释 = (s) => /^\s*(\/\/|\*|\/\*)|\{\/\*|\*\/\}/.test(s);

/**
 * 逐行标出「这一行开头是不是还在某个 JSX 标签的**属性区**里」。
 *
 * 为什么必须分得开：属性各占一行时，相邻两行也长得像「上一行末尾是中文、
 * 下一行开头是中文」——`能改正文` 换行 `模式={['scroll', …]}` 就是这么被
 * 第一版误判成一句话的（并起来会把两个 prop 变成一个不存在的 prop）。
 * 那两行**不是文本节点**，中间根本没有空格可折。
 *
 * 认法：扫过整份文本，`<` 后面紧跟字母 / `/` / `>` 才算开标签（`{a < b}` 那种
 * 比较运算后面是空格，不算），`>` 关标签；字符串和注释里的尖括号不作数。
 *
 * ⚠️ **标签里还要盯花括号深度**：属性值可以是表达式，而表达式里到处是 `>`——
 * `收起={() => 切换('设置')}` 那个箭头的 `>` 一被当成关标签，
 * 下面两行中文 prop 立刻被读成「一句话的两个半句」，于是假阳性。
 * （真踩到的：给 `ReadSettingsPanel` 加一个 `收起` prop 之后，
 * 自检里那个「必须不被报出来」的诱饵当场被报出来了。）
 * 深度大于 0 时 `>` 不关标签、`<` 不开标签。
 */
function 标签内(文本) {
  const 行内 = [];
  let 在标签 = false;
  let 深度 = 0;
  let 引号 = null;
  let 块注释 = false;
  for (const 原始行 of 文本.split('\n')) {
    行内.push(在标签);
    for (let i = 0; i < 原始行.length; i++) {
      const c = 原始行[i];
      if (块注释) { if (c === '*' && 原始行[i + 1] === '/') 块注释 = false; continue; }
      if (引号) { if (c === '\\') i++; else if (c === 引号) 引号 = null; continue; }
      if (c === '/' && 原始行[i + 1] === '*') { 块注释 = true; i++; continue; }
      if (c === '/' && 原始行[i + 1] === '/') break;
      if (c === '"' || c === "'" || c === '`') { 引号 = c; continue; }
      if (c === '{' || c === '(' || c === '[') { if (在标签) 深度++; continue; }
      if (c === '}' || c === ')' || c === ']') { if (在标签 && 深度 > 0) 深度--; continue; }
      if (在标签 && 深度 > 0) continue;          // 表达式里面的尖括号都不算
      if (c === '<' && /[A-Za-z/ >]/.test(原始行[i + 1] ?? '')) { 在标签 = true; 深度 = 0; }
      else if (c === '>' && 在标签) { 在标签 = false; 深度 = 0; }
    }
  }
  return 行内;
}

/**
 * 一段源码文本 → 可疑的「第 N 行末 + 第 N+1 行首」对。
 * 单独抽出来是为了自检能喂它一段假源码（不碰真文件）。
 */
export function 扫文本(文件, 文本) {
  const 行 = 文本.split(/\r?\n/);
  const 在属性区 = 标签内(文本);
  const 报 = [];
  let inBlock = false;
  for (let i = 0; i + 1 < 行.length; i++) {
    const a = 行[i];
    const 开 = (a.match(/\/\*/g) || []).length;
    const 闭 = (a.match(/\*\//g) || []).length;
    const 在块注释里 = inBlock;
    inBlock = inBlock ? 闭 <= 开 : 开 > 闭;
    if (在块注释里 || 是注释(a) || 是注释(行[i + 1])) continue;
    if (在属性区[i]) continue;
    const 上 = a.replace(/\/\/.*$/, '').replace(/\/\*[\s\S]*?\*\//g, '').trimEnd();
    const 下 = 行[i + 1].trim();
    // 上一行以引号收尾 = 整个属性值或字符串字面量，两行之间没有 JSX 那套折叠
    const 标点结尾 = 行尾是全角标点.test(上);
    if (/[=+*/<>]$/.test(上.slice(-1))) continue;
    if (!(标点结尾 || 行尾是中文.test(上))) continue;
    // 下一行开头是 JS 语法（`+` 拼接、`}` 收尾、引号起的字符串）时不是同一个文本节点；
    // 是 `<` 或 `{` 时它是**另一个 child**（元素或表达式）——文本自己会被裁掉行尾空白，
    // 不产生那道缝：缝只出现在**两段文本并成一个 child** 的时候
    if (/^[+})\]?:;&|/<{]/.test(下) || /^["'`]/.test(下)) continue;
    // 行尾是中文时，下一行也得是中文才算同一句话；行尾是全角标点时，
    // 下一行哪怕接英文也照样多一道缝（「…完整阅读，␣pdf / epub…」）
    if (!标点结尾 && !行首是中文.test(下)) continue;
    报.push({ 文件, 行号: i + 1, 上: 上.slice(-24), 下: 下.slice(0, 24) });
  }
  return 报;
}

/* 直接跑才自检和扫全量；被 import 时只出 `扫文本`——复用这份判据的是一次性修复脚本，
   按仓库的规矩它们待在 gitignore 的临时目录里，所以这里**不点名文件**：
   点一个干净克隆里不存在的路径，`stale-refs` 就在 CI 上报错，而本文件开头那条说的就是
   「一句需要豁免才能存在的提醒，多半本来就不该那么写」。
   Windows 上 argv[1] 是反斜杠绝对路径，所以按文件名尾巴认。 */
if (/cjk-join\.mjs$/.test(process.argv[1] ?? '')) {
/* ── 自检：该抓的必须抓到，不该抓的必须不报 ── */
const 夹具 = [
  // 必须报：中文句子跨行
  '<p className="muted">清掉几种记录自己跟自己对不上的情况：没有文件的空记录、',
  '  有好几份却没定下用哪份的。</p>',
  // 必须报：**全角标点后面接英文**——那道缝照样在（首屏实拍量到的就是这一形）
  '<span>这类文本在书斋里完整阅读，',
  '  pdf / epub 有内置查看器。</span>',
  // 必须不报：英文（空格本来就是对的）
  '<p>Hello',
  '  world</p>',
  // 必须不报：两行之间隔着标签
  '<span>前面还有 {n} 章</span>',
  '<span>下面还有 {m} 章</span>',
  // 必须不报：下一行是**另一个元素**，文本自己裁掉行尾空白，没有那道缝
  '<p>正文变过，',
  '  <strong>要重新解析一次</strong>。</p>',
  // 必须不报：下一行是**表达式 child**，同上——缝只在两段文本并成一个 child 时才有
  '<p>没有符合分类「{这个分类?.name}」的书。',
  '  {带目录 && <>常见的原因是它没扫进来</>}</p>',
  // 必须不报：字符串拼接（`+` 不会插空格）
  "return '这本书的文件不见了（被删了，或者移到别处了）。'",
  "  + '扫描一次书库能把移过位置的认回来。';",
  // 必须不报：**两个中文 prop 各占一行**——它们不是文本节点，中间没有空格可折。
  // 这一条是被真实误报喂进来的：`能改正文` 换行 `模式={[…]}` 并起来会造出一个不存在的 prop
  '<ReadSettingsPanel',
  '  set={set}',
  '  能改正文',
  "  模式={['scroll', 'flow', 'page']}",
  '/>',
].join('\n');
/*
 * 箭头函数那一形**单独一份夹具**。和上面那份混在一起时它不报——
 * 前面某一行把标签状态带过来了，于是「去掉深度保护它照样不报」，
 * 一条不咬的诱饵比没有诱饵更糟（它会让下一个人以为这一形被看着）。
 * 单独喂才量得出：把 `标签内` 里那句深度保护拿掉，这一份当场报出第 4 行。
 */
const 夹具2 = [
  '<ReadSettingsPanel',
  "  收起={() => 切换('设置')}",
  '  set={set}',
  '  能改正文',
  "  模式={['scroll', 'flow', 'page']}",
  '/>',
].join('\n');
const 自检 = 扫文本('夹具.tsx', 夹具);
const 自检2 = 扫文本('夹具2.tsx', 夹具2);
const 该抓 = [
  ['空记录、', '中文句子跨行没抓到'],
  ['完整阅读，', '全角标点后面接英文那一形没抓到'],
];
const 抓到 = 该抓.filter(([标]) => !自检.some((r) => r.上.includes(标)));
const 误报 = 自检.filter((r) => !该抓.some(([标]) => r.上.includes(标)));
if (抓到.length) {
  console.error(`✗ 自检失败：${抓到.map(([, 话]) => 话).join('；')}——这条判据现在是死的，别当它存在`);
  process.exit(1);
}
if (误报.length) {
  console.error('✗ 自检失败：夹具里「本来就没毛病」的几行被误报了，判据画得太宽：');
  for (const r of 误报) console.error(`   ${r.文件}:${r.行号}  ${r.上} ⏎ ${r.下}`);
  process.exit(1);
}
if (自检2.length) {
  console.error('✗ 自检失败：属性值是箭头函数那一形被误报了（`=>` 的 `>` 不能关标签）：');
  for (const r of 自检2) console.error(`   ${r.文件}:${r.行号}  ${r.上} ⏎ ${r.下}`);
  process.exit(1);
}
console.log(`自检通过：夹具该抓的抓住了，几行诱饵都没误报`);

/* ── 真扫 ── */
const 全部 = [];
for (const f of 找文件(目录)) 全部.push(...扫文本(f, readFileSync(f, 'utf8')));
if (!全部.length) {
  console.log(`✔ ${找文件(目录).length} 个界面文件，中文句子没有跨行折出空格的`);
  process.exit(0);
}
console.log(`\n⚠ 中文句子中间会被折出一个半角空格（${全部.length} 处）——改法都是「两行并一行」，不改一个字：\n`);
for (const r of 全部) console.log(`  ${r.文件}:${r.行号}\n     …${r.上}␣${r.下}…`);
process.exit(1);
}
