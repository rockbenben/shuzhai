/**
 * 占位封面上那两个**算出来的**值：哪匹书衣、题签多大字。
 *
 * **为什么单独一个模块**：`Cover.tsx` 是 JSX，`node --test` 的原生剥类型不认它，
 * 所以放在里面的判据一条也测不到。而这两条都不是摆设——
 * 「同一本书永远同一色」原来在 `core/cover.ts` 有一条测试守着
 * （那份实现已经删了，它只被自己的测试调用过），字号那条更是一道解出来的不等式。
 * 同 `core/pacing.ts`：测不了的地方，把判据挪到测得了的地方去。
 */

/**
 * **书衣六色。**
 *
 * 没有封面的书不是「缺一张图」——那本 txt 的封面**从来就没人画过**。
 * 所以顶上来的不该是一张假的封面画，而是一件**装帧**：素色书衣 + 一张题签。
 * 这六个取自古籍书衣的染色（磁青、蟹壳青、官绿、秋香、赭石、绛），
 * 明度都压在同一档上，摆成一墙仍然是同一套东西，而不是六件事。
 *
 * ⚠️ **别退回「按书名算一个 0–360 的色相」**（这里原来就是那么写的）。
 * 三百六十个色相铺在 `--bg` 那张米纸上就是一把彩虹糖，而**九成的书架就是这块**
 * ——真实库 8287 本里只有 773 本有真封面。色相连续不是信息，是噪声。
 */
export const 书衣 = ['#2c3a52', '#2f5753', '#3d5741', '#5a5733', '#7a4d33', '#6b2f31'];

/**
 * 哪本书用哪匹布。**同一本书永远同一色**——书架看久了能靠颜色认书，
 * 这条是原来那版就有的判据，改的只是落点：从 360 个色相收成 6 匹布。
 * （360 能被 6 整除，所以后一步取模不引入偏斜。）
 */
export function 书衣色(title: string): string {
  let h = 0;
  for (const ch of title) h = (h * 31 + ch.codePointAt(0)!) % 360;
  return 书衣[h % 书衣.length];
}

/**
 * 书名在封面上占多大的地方，单位 `cqw`（封面自己宽度的百分之一；封面高 140cqw）。
 *
 * ⚠️ **别再把它挤到左边那条窄签里。** 前一版是「左上角一张题签」，为了躲开右上角
 * 那列角标，宽度被钉死在 36%——而当场数过用户的真实库：**8288 本里 8139 本
 * 一个角标都没有（98.2%）**，1.8% 有一个，全库只有一本有两个。
 * 也就是说那 36% 是为 1.8% 的卡片，把 98.2% 的书名压小了。
 * 现在字**居中、自适应**，宽度放到 84%；角标真的存在时才把顶边让下去
 * （让的是高度，不是宽度——角标是从上往下叠的一列）。
 */
const 左右留白 = 8;          // 单边，% of 宽
const 底留白 = 8;            // % of 高
const 顶留白 = 8;            // % of 高，没角标时
const 一个角标 = 12;         // % of 高。角标行高 21px / 封面高 183px ≈ 11.5，留一点富余
const 可用宽 = 100 - 左右留白 * 2;
const 行距 = 1.22;           // 竖排里 line-height 决定的是**列宽**

/**
 * 字号上下限，单位 `cqw`。
 * - **上限 26**：两三个字的书名能占到多大。再大就不像书名像海报了，
 *   而且短书名本来就该留白（真的封面也是这样）。131px 的最小卡片上是 34px。
 * - **下限 9**：131px 上约 12px 宋体，再小不是给人读的。
 *   够不着的那种长度会在 `题签文字` 那儿先截掉，不靠 CSS 裁。
 */
export const 字号上限 = 26;
export const 字号下限 = 9;

/** 有 b 个角标时，竖排能用的长度（cqw）。角标是往下叠的，所以吃的是**高**不是宽 */
function 可用长(角标数: number): number {
  const 顶 = 角标数 > 0 ? 4 + 角标数 * 一个角标 : 顶留白;
  return Math.max(一个角标, (100 - 顶 - 底留白) * 1.4);
}

/**
 * 书名用多大的字，单位 **`cqw`**。
 *
 * ⚠️ **用容器单位，不要拿 JS 算像素。** 原来那版拿 `width ?? 128` 当基准，
 * 而封面墙**根本不传 width**（格子说了算，`minmax(8.2rem, 1fr)`）——
 * 于是 2560 宽下卡片撑到两百多像素，字号还钉在 128 那一档上。
 *
 * 算法是**从大到小试**，不是解方程：一个字号先看一列排得下几个字，
 * 再看要几列、那么宽塞不塞得下。第一个塞得下的就是答案。
 * 比硬解 `ceil` 那个方程好读，也不会在边界上差一格。
 *
 * 真实库量出来（8288 本）：中位数 4 字，75% 分位 7 字，95% 分位 10 字，最长 29。
 * 这套数下 4 字 34px、10 字 29px、20 字 22px、29 字 18px（都按 131px 的最小卡片算）
 * ——上一版同样的位置是 21 / 17 / 13 / 12px。
 */
export function 字号(字数: number, 角标数 = 0): number {
  const 长 = 可用长(角标数);
  const n = Math.min(最多字数(角标数), Math.max(1, 字数));
  for (let s = 字号上限; s >= 字号下限; s -= 0.5) {
    const 每列 = Math.floor(长 / s);
    if (每列 < 1) continue;
    if (行距 * Math.ceil(n / 每列) * s <= 可用宽) return s;
  }
  return 字号下限;
}

/** 那个字号下排成几列——测试要用，界面上是浏览器自己折的 */
export function 列数(字数: number, 角标数 = 0): number {
  const s = 字号(字数, 角标数);
  const 每列 = Math.max(1, Math.floor(可用长(角标数) / s));
  return Math.ceil(Math.max(1, 字数) / 每列);
}

/**
 * **一张封面最多放得下多少字**：下限字号下，一列几个 × 塞得下几列。
 *
 * 真实库最长的书名 29 字，所以常规情况一本都碰不到——但用户随时能改书名，
 * 而**溢出的后果不是难看，是被裁**：多列竖排溢出走的是块方向，
 * `audit.mjs` 的「文字被硬切」会报，而屏幕上就是最左边那列凭空少半截。
 * 所以宁可自己截、明写一个省略号。
 */
export function 最多字数(角标数 = 0): number {
  const s = 字号下限;
  const 每列 = Math.floor(可用长(角标数) / s);
  const 最多列 = Math.floor(可用宽 / (行距 * s));
  return Math.max(1, 每列 * 最多列);
}

/** 封面上真正印出去的那串字：超过装得下的，截掉并补一个省略号 */
export function 封面文字(title: string, 角标数 = 0): string {
  const 字 = [...title];
  const 上限 = 最多字数(角标数);
  return 字.length <= 上限 ? title : 字.slice(0, 上限 - 1).join('') + '…';
}
