// 净化规则（spec §2.4）。**这是我们自己的规则集，不是从别处导来的。**
//
// 来历：一开始直接把「乌云净化」那 20 条翻译过来当内置。翻译本身没问题（正则都编译得过），
// 但那套规则**不适合这个应用**——它是给手机阅读器「顺手美化」用的，里面大量条目
// 根本不是清洗：
//
//   - `#04 星号修复` 用四千字的 JS 猜着把 `×××` 还原成脏话。那是**编造正文**。
//   - `#19 拆分长句` / `#20 拆分段落` 把作者的长句和段落拆开重排。那是**改写**。
//   - `#09–#12` 按自己的偏好把引号换成 `「」`、括号换成 `【】`。那是**口味**。
//   - `#01 数字标题` 把中文数字章节号转成阿拉伯数字。我们的章节标题来自自己的解析器，
//     根本不从正文里取。
//
// 铁律第 1 条说原文件只读，清洗是**运行时套规则**——但正文被悄悄改掉、吃掉，用户
// 一样发现不了，而且比改文件更难察觉。所以这个规则集只做一件事：
// **把不属于作者的东西去掉，一个字都不改写。**
//
// ── 默认开的几条是怎么定下来的 ──────────────────────────
//
// 不是照着别人的规则集抄的，是在用户真实书库（8000+ 本）里抽样量出来的：
// 抽 600 本的第 9 章，HTML、网址、`（本章完）`、求票、全角数字、零宽字符**全是 0%**；
// 命中率最高的两条是误报——39.7% 的「整行只有符号」其实是正文里独立成行的 `……`，
// 25% 的「连续横线」是对话里正常的破折号。**照搬那套规则只会伤到正文。**
//
// 真正的脏东西在末章：抽的 500 本里 **491 本（98%）**末尾有制作组页脚，长这样
//
//     ==========================================================
//     更多精校小说尽在知轩藏书下载：http://www.zxcs.me/
//     ==========================================================
//
// 于是默认开的就是能吃掉这三行、且实测不碰正文的那几条。
// 其余的（求票、作者的话、标点规整）在这个库里几乎不出现，但从网站抓的 txt 里很常见——
// 留着但**默认关**，用户对着 diff 预览自己开。
//
// ⚠️ 改这个文件前先想清楚：`（全文完）`、`（全书完）`、`（大结局）` 是**作者写的正文**，
// 抽样里到处都是。只有 `（本章完）` 是站点自动加的。差一个字，删掉的就是人家的结尾。

