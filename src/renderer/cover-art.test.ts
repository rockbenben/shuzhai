/**
 * 占位封面那两条算出来的判据。九成的书架是这块（真实库 8287 本里 773 本有真封面），
 * 而它画在 JSX 里、测不到——所以判据挪进了 `cover-art.ts`，这里守着它。
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { 书衣, 书衣色, 字号, 列数, 封面文字, 最多字数, 字号上限, 字号下限, 排布, 题签列 } from './cover-art.ts';

test('同一本书永远同一色——不稳定的话书架每次打开颜色都在变', () => {
  const a = 书衣色('雪中悍刀行');
  assert.equal(a, 书衣色('雪中悍刀行'));
  assert.ok(书衣.includes(a), `${a} 不在那六匹布里`);
});

test('落点在那六匹布上，而且真的用得开', () => {
  // 随手一批真实书名，别全落到同一匹布上——那样颜色就不认书了
  const 书 = ['雪中悍刀行', '斗破苍穹', '白马啸西风', '琥珀之剑', '藏地密码', '光年',
    '天机', '闻香榭', '华娱', '魅生', '归途', '月下独行'];
  const 用到的 = new Set(书.map(书衣色));
  assert.ok(用到的.size >= 4, `12 本书只用到 ${用到的.size} 匹布`);
  for (const t of 书) assert.ok(书衣.includes(书衣色(t)));
});

test('空书名不炸，也得给一匹布', () => {
  assert.ok(书衣.includes(书衣色('')));
});

/*
 * 下面几条盯的是同一件事：**书名要读得清，排得下整张封面。**
 *
 * 状态标记早就不在封面上了（挪到了卡片下方的信息行），题签始终用整张封面——
 * 所以只有一档几何，不再按角标数分。这里照封面的留白复算一遍，和 `cover-art.ts`
 * 那份算式互为对照。
 */
const 可用宽 = 84;
const 行距 = 1.22;
const 可用长 = (100 - 8 * 2) * 1.4;

test('字号封在上下限之间', () => {
  for (const n of [0, 1, 2, 3, 5, 8, 12, 40, 200]) {
    const s = 字号(n);
    assert.ok(s <= 字号上限, `${n} 字算出 ${s}，超过上限`);
    assert.ok(s >= 字号下限, `${n} 字算出 ${s}，低于下限`);
  }
});

test('字越多字号不许反而变大', () => {
  let 上一个 = Infinity;
  for (let n = 1; n <= 60; n++) {
    const s = 字号(n);
    assert.ok(s <= 上一个, `${n} 字算出 ${s}，比 ${n - 1} 字的 ${上一个} 还大`);
    上一个 = s;
  }
  assert.equal(字号(3), 字号上限, '三个字该吃满上限');
});

test('排得下：列数乘列宽不许超出可用宽，也不许有排不完的字', () => {
  for (let n = 1; n <= 最多字数(); n++) {
    const s = 字号(n);
    const 每列 = Math.floor(可用长 / s);
    assert.ok(每列 >= 1, `${n} 字：一列一个字都排不下`);
    const 列 = Math.ceil(n / 每列);
    assert.ok(列 * 每列 >= n);
    assert.ok(行距 * 列 * s <= 可用宽 + 1e-9,
      `${n} 字要 ${列} 列共 ${(行距 * 列 * s).toFixed(1)}cqw，超过 ${可用宽}`);
  }
});

/*
 * ⚠️ **这条是「看不清」那次的守卫，而且门槛是照着真实分布定的。**
 * 8288 本量出来：中位数 4 字，75% 分位 7，90% 分位 9，95% 分位 10，最长 29。
 * 131px 是最小卡片（`.wall` 的 `minmax(8.2rem, 1fr)`），1cqw = 1.31px。
 * 谁把版式改回窄条，这几条会当场红——而不用等人报「字太小」。
 */
test('真实库那几档常见长度，在最小卡片上都得读得清', () => {
  for (const [字数, 最低px] of [[4, 30], [7, 30], [9, 28], [10, 28], [12, 26], [20, 20], [29, 17]] as const) {
    const px = 字号(字数) * 1.31;
    assert.ok(px >= 最低px, `${字数} 字在最小卡片上只有 ${px.toFixed(1)}px，低于 ${最低px}px`);
  }
});

test('列数：短的一列，长的往左边续', () => {
  assert.equal(列数(3), 1);
  assert.ok(列数(12) >= 2, '12 个字还挤在一列里，那就是又锁回去了');
  assert.ok(列数(29) >= 2);
});

test('超过一张封面装得下的，自己截掉并补省略号——不留给 CSS 去裁', () => {
  const 短 = '雪中悍刀行';
  assert.equal(封面文字(短), 短, '装得下的一个字都不许动');
  const 长 = '书'.repeat(最多字数() + 10);
  const 出 = 封面文字(长);
  assert.equal([...出].length, 最多字数(), '截完还是超长，那 CSS 照样会裁');
  assert.ok(出.endsWith('…'), '截了要说一声');
});

test('真实库最长那本（29 字）不该被截', () => {
  assert.ok(最多字数() >= 29, `整张封面只装得下 ${最多字数()} 字`);
});

/*
 * **断列是我们算的，不是浏览器折的**（`题签列` + `.cover-title` 的 `nowrap`）。
 * 起因是实拍：长书名甩成「…到会换」/「行」——最左边一列只剩一个字，
 * 像掉了字。横排那条「最后一行只剩一个字」的走查判据量不到竖排
 * （探针按横排归并矩形），所以这条只能钉在这儿。
 */
test('题签不许甩出只剩一个字的孤列', () => {
  for (let n = 2; n <= 最多字数(); n++) {
    const 列 = 排布(n);
    assert.equal(列.reduce((a, b) => a + b, 0), n, `${n} 字排完字数变了：${列.join('+')}`);
    assert.ok(
      列.length === 1 || 列[列.length - 1] >= 2,
      `${n} 字排成 ${列.join('+')}，最后一列只剩 ${列[列.length - 1]} 个字`,
    );
    const 每列 = Math.floor(可用长 / 字号(n));
    assert.ok(Math.max(...列) <= 每列, `${n} 字有一列超过这个字号塞得下的 ${每列} 个字：${列.join('+')}`);
    assert.ok(行距 * 列.length * 字号(n) <= 可用宽 + 1e-9, `${n} 字 ${列.length} 列横着塞不下`);
  }
  // 测试库里真有的那本：20 字，旧排法是 6+6+6+2（末列两个字还勉强），
  // 而 19 字那档旧排法是 6+6+6+1——孤列。匀开之后每列差不过一个字
  assert.deepEqual(排布(20), [5, 5, 5, 5]);
  assert.deepEqual(排布(19), [5, 5, 5, 4]);
});

test('题签列拼回去就是封面上那串字，第一列是最长的那一列', () => {
  const 书 = '这本书名字特别长长长长长长长长到会换行';
  const 列 = 题签列(书) ?? [];
  assert.ok(题签列(书), '纯汉字书名该自己算列，不该交回浏览器');
  assert.equal(列.join(''), 封面文字(书), '拆完再拼回去少了一个字');
  assert.ok(列.length >= 2, '这么长的书名该不止一列');
  assert.ok(列[0].length >= 列[列.length - 1].length, '长的列要排在右边（竖排从右往左读）');
  assert.deepEqual(题签列('琥珀之剑'), ['琥珀之剑'], '四个字正好一列，不许被拆');
  assert.deepEqual(题签列('雪中悍刀行'), ['雪中悍', '刀行'], '五个字排 3+2，末列不许只剩一个');
  assert.equal((题签列('') ?? []).join(''), '', '空书名不炸');
});

test('带拉丁 / 数字的书名交回浏览器折，不拿没量过的字宽去猜', () => {
  // 按字数匀开会把「PDF」切成「一本PD」/「F电子书」——比旧排法切在汉字上更难看。
  // 一个旋转的字母在竖排里到底占多宽**没量过**，所以这一类返回 null，界面走旧那条路
  for (const 书 of ['一本PDF电子书', '一本EPUB电子书', 'The Hobbit 霍比特人', '2024年度精选']) {
    assert.equal(题签列(书), null, `${书} 该交回浏览器，而不是我们自己按字数切`);
  }
  assert.deepEqual(题签列('剑来'), ['剑来'], '纯汉字书名才走自己算的那条路');
});
