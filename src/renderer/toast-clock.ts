/**
 * 通知的「到点自己走」——**纯计算，好测**。
 *
 * ⚠️ **为什么不住在 `Toast.tsx` 里：** 那是 `.tsx`，`node --test` 的原生剥类型
 * 不认它（同 `cover-art.ts` 那个理由），所以判据得住在 `.ts` 里才钉得住。
 *
 * ⚠️ **寿命从「这条通知出现的那一刻」起算，不从「它挂在屏幕上的这段时间」起算。**
 *
 * 原来计时器住在 `Toast` 组件里，而 App 在 `reading` / `viewing` 非空时
 * **整个 return 掉书架**——通知浮层跟着卸载，计时器跟着没了；退回书架时它
 * 重新挂上、**重新等满一整个 `auto`**。症状是用户报的那句：「扫描完成后我点进
 * 一本书，过了很久返回书架，扫描通知还在」——它不是「一直在」，是**重新活了一遍**。
 *
 * 所以：**到期时刻 = 出生时刻 + 寿命**，两者都由调用方给，组件只管到期。
 */

/**
 * 一条通知到点走的时刻（墙上的钟，epoch ms）。
 *
 * `auto` 为 0 → **没有到期时刻**（永不走）。那种通知只许用在「关掉就找不回」的
 * 场合（判据在 `App.tsx` 的 `ACTIONABLE_TOAST_MS` 注释上）。
 */
export function 到期时刻(born: number, auto: number): number | null {
  return auto > 0 ? born + auto : null;
}

/**
 * 还剩多久就走。**过了就是 0**，不是负数。
 *
 * ⚠️ **「过了就是 0」不是细节**——它就是「书架被卸载过一阵再回来，那条通知
 * 早就该走了」这条判据的算法：算出来的 0 就是「别画出来了」。
 */
export function 还能活多久(到期: number, now: number): number {
  return Math.max(0, 到期 - now);
}

/**
 * 停住了这么久 → 到期时刻往后推这么久。
 *
 * ⚠️ **是「往后推」，不是「重新等满一个 `auto`」。**
 *
 * 这条是量过的：停在第 9 秒、压住 6 秒再移开，「重新计时」要再等 12.2 秒，
 * 「接着走」只要 2.8 秒（数字在 `docs/lessons.md`「暂停被写成了重新计时」那节）。
 * 推后之后算出来的剩余，正好是「停住那一刻还剩多少」。
 */
export function 推后(到期: number, 停住多久: number): number {
  return 到期 + 停住多久;
}

/**
 * 停住了一会儿之后，移开时还剩多少。
 *
 * ⚠️ **停住的那段时间不算进寿命里**——通知是「停不住的时间」满 N 秒就走，
 * 不是「从出现到消失」满 N 秒。所以推后的是到期时刻，不是剩余时间。
 */
export function 移开后还剩(到期: number, 停住多久: number, now: number): number {
  return 还能活多久(推后(到期, 停住多久), now);
}
