/**
 * 占位封面那两条算出来的判据。九成的书架是这块（真实库 8287 本里 773 本有真封面），
 * 而它画在 JSX 里、测不到——所以判据挪进了 `cover-art.ts`，这里守着它。
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { 书衣, 书衣色, 题签字号, 字号上限, 字号下限 } from './cover-art.ts';

test('同一本书永远同一色——不稳定的话书架每次打开颜色都在变', () => {
  const a = 书衣色('雪中悍刀行');
  assert.equal(a, 书衣色('雪中悍刀行'));
  assert.ok(书衣.includes(a), `${a} 不在那六匹布里`);
});

test('落点在那六匹布上，而且真的用得开', () => {
  // 随手一批真实书名，别全落到同一匹布上——那样颜色就不认书了
  const 书 = ['雪中悍刀行', '斗破苍穹', '白马啸西风', '琥珀之剑', '藏地密码', '光年',
    '天机', '闻香榭', '华娱', '魅生', '归途', '月下独行'];
  const 用到的 = new Set(书.map(书衣色));
  assert.ok(用到的.size >= 4, `12 本书只用到 ${用到的.size} 匹布`);
  for (const t of 书) assert.ok(书衣.includes(书衣色(t)));
});

test('空书名不炸，也得给一匹布', () => {
  assert.ok(书衣.includes(书衣色('')));
});

/*
 * ⚠️ **上限那条不是「凑个数」，它是题签和角标不打架的唯一保证。**
 * 题签宽 1.54em，左边距 9%——19cqw 时右缘 38.3%，而最宽的角标从 47.6% 起排。
 * 谁把上限调上去，`audit.mjs` 的「封面上的字被角标压住」才会红，
 * 而那要跑一趟走查才知道。这里当场就红。
 */
test('字号封在上下限之间，一个字的书名也不许顶破上限', () => {
  for (const n of [0, 1, 2, 3, 5, 8, 12, 40, 200]) {
    const s = 题签字号(n);
    assert.ok(s <= 字号上限, `${n} 个字算出 ${s}，超过上限 ${字号上限}`);
    assert.ok(s >= 字号下限, `${n} 个字算出 ${s}，低于下限 ${字号下限}`);
  }
});

test('字越多签上的字越小（不许反过来，也不许一直不变）', () => {
  assert.ok(题签字号(6) > 题签字号(8));
  assert.ok(题签字号(8) > 题签字号(10));
  // 短书名一律吃满上限：四个字的签和三个字的签，字一样大，只是签短一截
  assert.equal(题签字号(3), 字号上限);
  assert.equal(题签字号(4), 字号上限);
});

test('题签装得下：字数 × 字号 加上内边距不超过签的最大长度', () => {
  // 106.4cqw = 76%（max-height）× 140%（1 / 1.4 的封面），内边距 0.52em
  for (let n = 1; n <= 11; n++) {
    const s = 题签字号(n);
    assert.ok(n * s + 0.52 * s <= 106.4, `${n} 个字在 ${s}cqw 下装不下，会被截掉`);
  }
});
