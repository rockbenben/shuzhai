// 随应用发布的在线朗读引擎——**现在一个都没有，这是有意的。**
//
// 起因是用户的一句话：**「有些设置是私人化的，可能不方便分享，比如 tts 源，
// 默认设置只是系统离线语言，我其他加入的源只放在个人设置里。」**
//
// 这里原来硬编码着 88 个引擎。那份名单是**用户自己**从五份「阅读」配置
// （共 281 条）里筛出来的：逐个域名探活，11 个域名只剩 2 个还活着
// （vercel 代理 402 欠费、搜狗连不上、百度要 token、有道 688、google.cn 404），
// 活着的再逐条实测「发两个字能不能拿回音频」，最后剩下那 88 个全是思必驰。
// 那是**他的东西**，跟着代码一起发出去不合适。
//
// 现在它们存在他自己的库里（`app_setting` 的 `tts.userEngines`，
// 见 `tts-custom.ts`）。别人装上这个应用，默认只有**系统离线语音**——
// 不外发一个字；想用在线引擎，自己导一份 `httpTTS.json` 进来。
//
// **这个数组留着不删**，因为它是个口子：哪天真有一个我们自己有权分发的引擎
// （比如自己搭的），放这儿就行，`rpc.ts` 的 `ttsEngines()` 会把它拼在用户
// 那份前面。删掉这个文件的话，那个位置就得临时再造一个。
//
// 三条硬性限制，一条都没松（它们现在管的是**用户导进来的**那些）：
//
// 1. **不执行配置里的任何 JS。** 原配置的 URL 模板可以写 `{{java.xxx}}`、
//    `loginUrl` / `loginCheckJs` 里更是任意代码。这些文件是别人给的，
//    执行它们等于跑陌生人的代码。只认「把 speakText 做 URI 编码」这一种模板，
//    其余一律不收：把关的是 `tts.ts` 的 `validEngine`（只许出现一个 `{text}`，
//    URL 里残留任何 `{{ }}` 都判不合法），填值的是同文件的 `renderUrl`。
//    ⚠️ 这一关**导入那头和取用那头各过一遍**（`importLegadoTts` / `parseEngines`）：
//    存进去的那一列用户能用文本编辑器改，也会跟着备份走。
// 2. **在线引擎会把正文发到第三方服务器。** 界面上必须说清楚，而且默认用
//    系统语音（Chromium 自带的 speechSynthesis，离线、不外发）。
//    **这一条现在是由「默认一个在线引擎都没有」兑现的，比一句提示硬。**
// 3. **这些是陌生人的服务器，随时会挂。** 上面那份探活结果就是证据——
//    九成的域名已经死了。所以在线引擎失败时要退回系统语音，不能让朗读直接哑掉。

export interface TtsEngine {
  id: string;
  name: string;
  /** `{text}` 会被替换成 URI 编码后的正文 */
  url: string;
  /** 有些服务要双重编码（原配置里的 `java.encodeURI(java.encodeURI(...))`） */
  double: boolean;
  contentType: string;
  /**
   * 发 POST 的那些（「阅读」里写成 `地址,{"method":"POST","body":"..."}`）。
   * 不填就是 GET。**百度那条就是 POST**，正文在 body 里而不是地址里。
   */
  method?: 'POST';
  /**
   * POST 的请求体。两种形状都有：form（`a=1&b=2`，百度）和 **SSML/XML**（Azure）。
   * `{text}` 在这儿而不是地址里。
   * ⚠️ 和地址一样，**里面绝不许留 `{{ }}`**——那是没转换干净的 JS。
   */
  body?: string;
  /**
   * 请求头。**Azure 那类非要不可**：`Ocp-Apim-Subscription-Key` 是用户自己的
   * 订阅密钥，`Content-Type: application/ssml+xml` 决定 body 怎么解析，
   * 少一个就是 400/401。
   *
   * ⚠️ 原来这里刻意不收 header（「别人给的文件，多一个可写的字段就多一个洞」），
   * **但那个判断经不起推敲**：这份配置本来就能往任意主机发任意 body，
   * 多一个 header 并不多给它什么——而且应用**没有**任何这些主机的凭据可被借用，
   * 密钥是配置自己带的。不收的代价倒是实打实的：一整类引擎用不了。
   */
  headers?: Record<string, string>;
}

export const BUILTIN_TTS: TtsEngine[] = [];
