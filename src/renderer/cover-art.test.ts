/**
 * 占位封面那两条算出来的判据。九成的书架是这块（真实库 8287 本里 773 本有真封面），
 * 而它画在 JSX 里、测不到——所以判据挪进了 `cover-art.ts`，这里守着它。
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { 书衣, 书衣色, 字号, 列数, 封面文字, 最多字数, 字号上限, 字号下限 } from './cover-art.ts';

test('同一本书永远同一色——不稳定的话书架每次打开颜色都在变', () => {
  const a = 书衣色('雪中悍刀行');
  assert.equal(a, 书衣色('雪中悍刀行'));
  assert.ok(书衣.includes(a), `${a} 不在那六匹布里`);
});

test('落点在那六匹布上，而且真的用得开', () => {
  // 随手一批真实书名，别全落到同一匹布上——那样颜色就不认书了
  const 书 = ['雪中悍刀行', '斗破苍穹', '白马啸西风', '琥珀之剑', '藏地密码', '光年',
    '天机', '闻香榭', '华娱', '魅生', '归途', '月下独行'];
  const 用到的 = new Set(书.map(书衣色));
  assert.ok(用到的.size >= 4, `12 本书只用到 ${用到的.size} 匹布`);
  for (const t of 书) assert.ok(书衣.includes(书衣色(t)));
});

test('空书名不炸，也得给一匹布', () => {
  assert.ok(书衣.includes(书衣色('')));
});

/*
 * 下面几条盯的是同一件事：**书名要读得清，而且不许压到角标上。**
 *
 * 这两条曾经互相打架——上一版为了躲角标，把书名钉死在左上角一条 36% 宽的签里，
 * 于是长书名只能靠缩字号顶（10 字掉到 12.7px）。当场数过真实库：
 * **8288 本里 8139 本一个角标都没有（98.2%）**，1.8% 有一个，全库只有一本有两个。
 * 所以现在按角标数分开算：没角标就用整张封面，有角标才把顶边让下去。
 */
const 可用宽 = 84;
const 行距 = 1.22;
const 可用长 = (b: number) => Math.max(12, (100 - (b > 0 ? 4 + b * 12 : 8) - 8) * 1.4);

test('字号封在上下限之间', () => {
  for (const b of [0, 1, 2]) {
    for (const n of [0, 1, 2, 3, 5, 8, 12, 40, 200]) {
      const s = 字号(n, b);
      assert.ok(s <= 字号上限, `${n} 字 ${b} 角标算出 ${s}，超过上限`);
      assert.ok(s >= 字号下限, `${n} 字 ${b} 角标算出 ${s}，低于下限`);
    }
  }
});

test('字越多字号不许反而变大', () => {
  let 上一个 = Infinity;
  for (let n = 1; n <= 60; n++) {
    const s = 字号(n);
    assert.ok(s <= 上一个, `${n} 字算出 ${s}，比 ${n - 1} 字的 ${上一个} 还大`);
    上一个 = s;
  }
  assert.equal(字号(3), 字号上限, '三个字该吃满上限');
});

test('排得下：列数乘列宽不许超出可用宽，也不许有排不完的字', () => {
  for (const b of [0, 1, 2]) {
    for (let n = 1; n <= 最多字数(b); n++) {
      const s = 字号(n, b);
      const 每列 = Math.floor(可用长(b) / s);
      assert.ok(每列 >= 1, `${n} 字 ${b} 角标：一列一个字都排不下`);
      const 列 = Math.ceil(n / 每列);
      assert.ok(列 * 每列 >= n);
      assert.ok(行距 * 列 * s <= 可用宽 + 1e-9,
        `${n} 字 ${b} 角标要 ${列} 列共 ${(行距 * 列 * s).toFixed(1)}cqw，超过 ${可用宽}`);
    }
  }
});

/*
 * ⚠️ **这条是「看不清」那次的守卫，而且门槛是照着真实分布定的。**
 * 8288 本量出来：中位数 4 字，75% 分位 7，90% 分位 9，95% 分位 10，最长 29。
 * 131px 是最小卡片（`.wall` 的 `minmax(8.2rem, 1fr)`），1cqw = 1.31px。
 * 谁把版式改回窄条，这几条会当场红——而不用等人报「字太小」。
 */
test('真实库那几档常见长度，在最小卡片上都得读得清', () => {
  for (const [字数, 最低px] of [[4, 30], [7, 30], [9, 28], [10, 28], [12, 26], [20, 20], [29, 17]] as const) {
    const px = 字号(字数) * 1.31;
    assert.ok(px >= 最低px, `${字数} 字在最小卡片上只有 ${px.toFixed(1)}px，低于 ${最低px}px`);
  }
});

test('98.2% 的卡片没有角标，不该跟着 1.8% 一起挨压', () => {
  // 同样的书名，没角标时必须比有角标时排得开——这就是把角标数传进来的全部理由
  for (const n of [10, 16, 20]) {
    assert.ok(字号(n, 0) >= 字号(n, 1), `${n} 字：没角标反而更小`);
  }
  // 角标少的时候两边可能算出同一个字号（让掉那点高度还排得开），所以拿够多的角标比：
  // 只要「让位」这件事真的发生了，堆到 3 个必然把字号压下来
  assert.ok(字号(29, 0) > 字号(29, 3), '角标堆到 3 个还一样大，那说明根本没让位');
  for (const n of [10, 20, 29]) {
    let 上一个 = Infinity;
    for (let b = 0; b <= 5; b++) {
      const s = 字号(n, b);
      assert.ok(s <= 上一个, `${n} 字：${b} 个角标反而比 ${b - 1} 个排得开`);
      上一个 = s;
    }
  }
});

test('列数：短的一列，长的往左边续', () => {
  assert.equal(列数(3), 1);
  assert.ok(列数(12) >= 2, '12 个字还挤在一列里，那就是又锁回去了');
  assert.ok(列数(29) >= 2);
});

test('超过一张封面装得下的，自己截掉并补省略号——不留给 CSS 去裁', () => {
  const 短 = '雪中悍刀行';
  assert.equal(封面文字(短), 短, '装得下的一个字都不许动');
  const 长 = '书'.repeat(最多字数() + 10);
  const 出 = 封面文字(长);
  assert.equal([...出].length, 最多字数(), '截完还是超长，那 CSS 照样会裁');
  assert.ok(出.endsWith('…'), '截了要说一声');
});

test('真实库最长那本（29 字）不该被截，哪怕它还挂着一个角标', () => {
  assert.ok(最多字数(0) >= 29, `没角标时只装得下 ${最多字数(0)} 字`);
  assert.ok(最多字数(1) >= 29, `有一个角标时只装得下 ${最多字数(1)} 字`);
});
