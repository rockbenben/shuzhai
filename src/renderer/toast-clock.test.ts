import { test } from 'node:test';
import assert from 'node:assert/strict';
import { 到期时刻, 还能活多久, 推后, 移开后还剩 } from './toast-clock.ts';

/*
 * **通知的寿命按墙上的钟算，不按「它挂在屏幕上的这段时间」算。**
 *
 * 症状是用户报的那句：「扫描完成后我点进一本书，过了很久返回书架，扫描通知还在」。
 * 看着像「通知一直在」，其实不是——App 在阅读器里会整个 return 掉书架，通知浮层
 * 跟着卸载，计时器跟着没了；退回书架时它重新挂上、**重新等满一整个 `auto`**。
 * 所以它是「重新活了一遍」。
 *
 * 这几条钉的是那个算法：出生时刻 + 寿命 = 到期时刻，而到期时刻是**绝对的**。
 */

/** 通报 12 秒（`App.tsx` 里那个 `12000`） */
const 通报 = 12_000;

test('寿命从出生那一刻算，到期时刻是绝对的', () => {
  assert.equal(到期时刻(1_000, 通报), 13_000);
  assert.equal(到期时刻(0, 通报), 12_000);
});

test('auto = 0 是「永不走」，不是「马上走」', () => {
  assert.equal(到期时刻(1_000, 0), null);
});

test('过了就是 0，不是负数', () => {
  assert.equal(还能活多久(13_000, 1_000), 12_000);
  assert.equal(还能活多久(13_000, 13_000), 0);
  assert.equal(还能活多久(13_000, 99_000), 0, '过期了不能算出负数');
});

test('**书架被卸载过一阵再回来，那条通知已经过期**（这次修的那条）', () => {
  // 扫描完成 → 通知出生（0 毫秒）→ 用户 3 秒时点进一本书（书架整个卸载，
  // 通知浮层跟着没了）→ 30 分钟后退回书架。
  const 到期 = 到期时刻(0, 通报)!;
  assert.equal(还能活多久(到期, 3_000), 9_000, '刚点进书时它还剩 9 秒');
  assert.equal(还能活多久(到期, 30 * 60_000), 0, '半小时后回来，它早该走了');
});

test('停住是把到期时刻往后推，不是重新等满一个 auto', () => {
  // 停在第 9 秒、压住 6 秒再移开：剩的是「停住那一刻的 3 秒」，
  // 不是重新等满 12 秒（实测 12241ms vs 2800ms，见 docs/lessons.md）。
  const 到期 = 到期时刻(0, 通报)!;
  assert.equal(移开后还剩(到期, 6_000, 15_000), 3_000);
  assert.equal(推后(到期, 6_000), 18_000);
});

test('停住的那段时间不算进寿命里', () => {
  // 停 6 秒之后，这条通知一共活了 12 + 6 = 18 秒——其中只有 12 秒是「停不住的」。
  const 到期 = 到期时刻(0, 通报)!;
  assert.equal(还能活多久(推后(到期, 6_000), 18_000), 0);
});
