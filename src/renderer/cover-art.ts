/**
 * 占位封面上那两个**算出来的**值：哪匹书衣、题签多大字。
 *
 * **为什么单独一个模块**：`Cover.tsx` 是 JSX，`node --test` 的原生剥类型不认它，
 * 所以放在里面的判据一条也测不到。而这两条都不是摆设——
 * 「同一本书永远同一色」原来在 `core/cover.ts` 有一条测试守着
 * （那份实现已经删了，它只被自己的测试调用过），字号那条更是一道解出来的不等式。
 * 同 `core/pacing.ts`：测不了的地方，把判据挪到测得了的地方去。
 */

/**
 * **书衣六色。**
 *
 * 没有封面的书不是「缺一张图」——那本 txt 的封面**从来就没人画过**。
 * 所以顶上来的不该是一张假的封面画，而是一件**装帧**：素色书衣 + 一张题签。
 * 这六个取自古籍书衣的染色（磁青、蟹壳青、官绿、秋香、赭石、绛），
 * 明度都压在同一档上，摆成一墙仍然是同一套东西，而不是六件事。
 *
 * ⚠️ **别退回「按书名算一个 0–360 的色相」**（这里原来就是那么写的）。
 * 三百六十个色相铺在 `--bg` 那张米纸上就是一把彩虹糖，而**九成的书架就是这块**
 * ——真实库 8287 本里只有 773 本有真封面。色相连续不是信息，是噪声。
 */
export const 书衣 = ['#2c3a52', '#2f5753', '#3d5741', '#5a5733', '#7a4d33', '#6b2f31'];

/**
 * 哪本书用哪匹布。**同一本书永远同一色**——书架看久了能靠颜色认书，
 * 这条是原来那版就有的判据，改的只是落点：从 360 个色相收成 6 匹布。
 * （360 能被 6 整除，所以后一步取模不引入偏斜。）
 */
export function 书衣色(title: string): string {
  let h = 0;
  for (const ch of title) h = (h * 31 + ch.codePointAt(0)!) % 360;
  return 书衣[h % 书衣.length];
}

/** 题签字号的上下限，单位 `cqw`。两个数都是量出来的，理由见 `题签字号` */
export const 字号上限 = 16;
export const 字号下限 = 8.5;

/**
 * 题签上那行字多大，单位 **`cqw`**（封面自己的宽度的百分之一，见 `shell.css`）。
 *
 * ⚠️ **用容器单位，不要拿 JS 算像素。** 原来那版拿 `width ?? 128` 当基准，
 * 而封面墙**根本不传 width**（格子说了算，`minmax(8.2rem, 1fr)`）——
 * 于是 2560 宽下卡片撑到两百多像素，字号还钉在 128 那一档上。
 *
 * 数是解出来的：题签最长 76% × 封面高（`1 / 1.4`）＝ 106.4cqw，减掉它自己的
 * 上下内边距 0.52em，`n` 个字要满足 `n·s + 0.52s ≤ 106.4`。留 4% 余量防四舍五入，
 * 反解出 `s ＝ 102 / (n + 0.52)`。
 *
 * ⚠️ **这个式子成立的前提是「一个汉字竖排占 1em」，而那取决于用哪张脸。**
 * 当场量的（同一段字，100px，`writing-mode: vertical-rl`）：
 * **宋体 500px、系统 serif 500px，而思源宋体 720px** —— 思源那份 `vhea` 带着
 * 一大截行间距，一个字占 **1.44em**。第一版把思源排在字体栈头一位，于是
 * 五个字的书名当场被截成三个，而屏幕上只看得到一个省略号，看不出是字体的事。
 * 所以 `shell.css` 那条字体栈**钉死宋体**（Windows 必有，缺了也退回 1em 的系统
 * serif）——别为了好看把思源塞回栈首，那会把这个式子整个作废。
 *
 * - **上限 16**：两件事同时定下的。① 再大题签就压到右上角那列角标上——题签宽
 *   1.54em ＝ 24.6cqw，左边距 9%，右缘落在 33.6%；角标里最宽的「文件不见了」
 *   63.1px 在 131px 的最小卡片上从 47.6% 起排（`audit.mjs` 的「封面上的字被角标
 *   压住」守着它）。② 题签是**贴上去的一条窄签**，不是竖幅——占到封面四分之一宽
 *   就够，再宽它就成了主体。
 * - **下限 8.5**：131px 的最小卡片上是 11px 宋体，再小就不是给人读的了。
 *   超长书名到这儿就截断出省略号——**完整书名印在封面正下方那一行**，
 *   题签本来也不负责说全。
 */
export function 题签字号(字数: number): number {
  return Math.min(字号上限, Math.max(字号下限, 102 / (Math.max(1, 字数) + 0.52)));
}
